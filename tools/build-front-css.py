#!/usr/bin/env python3
"""Build cheri-gallery/assets/css/front.css from components.css + gallery.css.

Every selector is scoped under .cg-page (the wrapper around the plugin's pages and shortcode),
so the website theme's button, link and heading styles can't override the gallery's look.
Selectors already starting with .cg-page, :root and @font-face are left as they are.

Run after editing either source:  python3 tools/build-front-css.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent / 'cheri-gallery' / 'assets' / 'css'
SCOPE = '.cg-page'


def scope_selector(sel):
    sel = sel.strip()
    if not sel or sel.startswith(SCOPE) or sel.startswith(':root') or sel.startswith('@'):
        return sel
    # Body-level state classes WordPress puts on <body>.
    m = re.match(r'^(\.admin-bar|body)\s+(.*)$', sel)
    if m:
        return f'{m.group(1)} {SCOPE} {m.group(2)}'
    return f'{SCOPE} {sel}'


def split_selectors(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += ch
    out.append(cur)
    return out


def process(css):
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    out, i = [], 0
    while i < len(css):
        j = css.find('{', i)
        if j < 0:
            break
        head = css[i:j].strip()
        if head.startswith('@media') or head.startswith('@supports'):
            depth, k = 1, j + 1
            while depth:
                depth += {'{': 1, '}': -1}.get(css[k], 0)
                k += 1
            out.append(head + ' {\n' + process(css[j + 1:k - 1]) + '}\n')
            i = k
            continue
        k = css.find('}', j)
        body = css[j + 1:k].strip()
        if head.startswith('@'):
            out.append(f'{head} {{ {body} }}\n')
        else:
            sels = ', '.join(scope_selector(s) for s in split_selectors(head))
            out.append(f'{sels} {{ {body} }}\n')
        i = k + 1
    return ''.join(out)


src = (ROOT / 'components.css').read_text() + '\n' + (ROOT / 'gallery.css').read_text()
(ROOT / 'front.css').write_text(
    '/* GENERATED by tools/build-front-css.py from components.css + gallery.css. Do not edit. */\n' + process(src)
)
print('wrote', ROOT / 'front.css')
